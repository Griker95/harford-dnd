-- Rasgos que no aparecen en los perfiles de referencia actuales. Se mantienen
-- por id estable para que nombres repetidos (p.ej. "Ataque Adicional") no
-- compartan accidentalmente la presentacion de otra clase.

local function TexturePath(icon)
    if not icon or icon == "" then return nil end
    if type(icon) == "number" then return icon end
    if type(icon) ~= "string" then return nil end
    if icon:sub(1, 10) == "Interface\\" then return icon end
    return "Interface\\Icons\\" .. icon
end

function Catalog.RegisterFeatures(entries)
    for id, icon in pairs(entries or {}) do
        Catalog.features[tostring(id)] = icon
    end
end

function Catalog.RegisterFeatureIfMissing(featureId, icon)
    local id = tostring(featureId or "")
    if id == "" or Catalog.features[id] then return end
    Catalog.features[id] = icon
end

function Catalog.RegisterSpells(entries)
    for id, candidates in pairs(entries or {}) do
        Catalog.spells[tostring(id)] = candidates
    end
end

function Catalog.RegisterSubclasses(entries)
    for classId, subclasses in pairs(entries or {}) do
        Catalog.subclasses[tostring(classId)] = subclasses
    end
end

function Catalog.GetFeatureIcon(featureId)
    return TexturePath(Catalog.features[tostring(featureId or "")])
end

function Catalog.GetSpellCandidates(spellId)
    return Catalog.spells[tostring(spellId or "")]
end

-- Icono del frame "Magia <Sub>" de los perfiles reales (Catalog.subclassSpells). Devuelve el
-- NOMBRE pelado, sin TexturePath: su consumidor es el IC de frame del About, que necesita
-- nombre (TRP3 antepone Interface\ICONS\ al texto tal cual).
function Catalog.GetSubclassSpellsIconName(classId, subclassId)
    return Catalog.subclassSpells[tostring(classId or "") .. "/" .. tostring(subclassId or "")]
end

function Catalog.GetSubclassIcon(classId, subclassId)
    local subclasses = Catalog.subclasses[tostring(classId or "")]
    return TexturePath(subclasses and subclasses[tostring(subclassId or "")])
end
